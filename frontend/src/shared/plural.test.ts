import { describe, expect, it } from 'vitest';
import { countLabel, plural } from './plural';

/** Независимые примеры проверяют исключение 11–14, переход сотни и знак числа. */
describe('plural', () => {
  it.each([
    [0, 'кадров'],
    [1, 'кадр'],
    [2, 'кадра'],
    [3, 'кадра'],
    [4, 'кадра'],
    [5, 'кадров'],
    [11, 'кадров'],
    [12, 'кадров'],
    [13, 'кадров'],
    [14, 'кадров'],
    [21, 'кадр'],
    [22, 'кадра'],
    [23, 'кадра'],
    [24, 'кадра'],
    [25, 'кадров'],
    [101, 'кадр'],
    [111, 'кадров'],
    [112, 'кадров'],
    [114, 'кадров'],
    [222, 'кадра'],
    [-1, 'кадр'],
    [-2, 'кадра'],
    [-11, 'кадров'],
    [-21, 'кадр'],
    [-22, 'кадра'],
    [0.5, 'кадра'],
    [1.5, 'кадра'],
    [2.5, 'кадра'],
    [-2.5, 'кадра']
  ] as const)('согласует %s', (count, expected) => {
    expect(plural(count, 'кадр', 'кадра', 'кадров')).toBe(expected);
    expect(countLabel(count, 'кадр', 'кадра', 'кадров')).toBe(`${count} ${expected}`);
  });
});
