package effects

// push — «Наезд»: медленное цифровое приближение к точке кадра или отъезд от неё поверх принятого видео.
// Это увеличение картинки, а не движение камеры: фон растёт вместе с героями, без параллакса, зато геометрия
// регулярного фона (разметка, плитка, окна) не плывёт, как у наезда, который рисует модель видео. Ход тот же,
// что у наезда сборки из опор (resample): точка центра остаётся на своём месте экрана, движение плавно
// разгоняется и тормозит между моментами плана start и end, до start кадр стоит как в начале, после end — как
// в конце. Отъезд начинается приближенным и раскрывается до всего кадра. Стоит в цепочке до света, дождя и
// зерна: капли и зерно ложатся на уже увеличенный кадр и сами не растут.
type push struct {
	amount, start, end, centerX, centerY float64
}

func init() {
	register(Kind{
		ID: "push", Title: "Наезд", Version: 1, Order: 5,
		Hint:     "Медленное приближение к выбранной точке кадра (наезд) или отдаление от неё (отъезд) поверх принятого видео. Применяйте, когда план с регулярным фоном (разметка, плитка, окна) снят неподвижной камерой, а на экране нужно движение к героям: наезд, который рисует модель видео, искажает такой фон. Это увеличение картинки: фон растёт вместе с героями, как при зуме объектива, а сильное увеличение смягчает кадр. Дождь и зерно ложатся уже на увеличенный кадр.",
		PlanTime: []string{"start", "end"},
		Params: []ParamSpec{
			{"amount", "Наезд (+) или отъезд (−), доля", -0.3, 0.3, 0.08, 0.005, "Насколько приблизить кадр за движение: 0,08 — наезд на 8% к центру, −0,1 — отъезд: план начинается приближенным на 10% и раскрывается до всего кадра; 0 — кадр неподвижен. Больше 0,1 по модулю картинка заметно мягче: видео увеличивается, новых подробностей в нём нет."},
			{"start", "Начало движения", 0, 1, 0, 0.01, "Когда наезд или отъезд начинается: до этого кадр стоит. Начало плана — движение с первого кадра."},
			{"end", "Конец движения", 0, 1, 1, 0.01, "Когда движение заканчивается, дальше кадр стоит. Конец плана — движение идёт до последнего кадра; раньше — успевает до смены плана или события."},
			{"center_x", "Центр по горизонтали", 0, 1, 0.5, 0.01, "К какой точке идёт наезд или от какой раскрывается отъезд, по горизонтали: 0 — левый край, 0,5 — центр, 1 — правый край. Обычно — лицо или руки главного героя."},
			{"center_y", "Центр по вертикали", 0, 1, 0.5, 0.01, "К какой точке идёт наезд или от какой раскрывается отъезд, по вертикали: 0 — верх, 0,5 — центр, 1 — низ."},
		},
		New: func(p Params, size Size) Effect {
			return &push{amount: p["amount"], start: p["start"], end: p["end"], centerX: p["center_x"], centerY: p["center_y"]}
		},
	})
}

// zoom — увеличение кадра ctx.Frame: 1 — весь кадр.
func (e *push) zoom(ctx *Context) float64 {
	progress := smoothstep(e.start, e.end, float64(ctx.Frame)/float64(max(1, ctx.Frames-1)))
	if e.amount < 0 {
		return 1 - e.amount*(1-progress)
	}
	return 1 + e.amount*progress
}

func (e *push) Apply(ctx *Context, f *Frame) {
	zoom := e.zoom(ctx)
	if zoom <= 1+1e-9 {
		return
	}
	out := resample(f, f.Width, f.Height, zoom, e.centerX, e.centerY, 0.5)
	copy(f.Pix, out.Pix)
}
