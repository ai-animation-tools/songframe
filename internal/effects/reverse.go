package effects

// reverse — «Реверс»: ролик плана задом наперёд. Пиксели он не меняет: кадры переставляет
// источник (OpenVideoReversed), который вызывающий выбирает по Kind.Reverse, поэтому в цепочке
// эффект ничего не делает.
type reverse struct{}

func init() {
	register(Kind{
		ID: "reverse", Title: "Реверс", Version: 1, Order: 0, Reverse: true, Params: []ParamSpec{},
		Hint: "Ролик плана идёт задом наперёд: последний кадр становится первым. Применяйте, когда план снят прямым ходом, а на экране нужен обратный — капли взлетают из лужи, свет уходит назад: модели видео обратную физику по описанию не делают. Остальные эффекты ложатся уже на развёрнутое видео: дождь в нём падает вниз, как обычно. Параметров нет. Сравнение «До» показывает кадр с тем же номером в исходном видео.",
		New:  func(Params, Size) Effect { return reverse{} },
	})
}

func (reverse) Apply(*Context, *Frame) {}
