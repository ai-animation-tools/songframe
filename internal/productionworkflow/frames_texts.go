// textImagesPrompt — промпт задания опор провайдера-агента:
// инструкция и формат ответа генератора; абзацы об утверждённых кадрах и замечаниях — только при
// их наличии; абзац о кадрах других планов — только если они среди копий; абзац о фактах кадра и
// схеме — только у плана с точкой съёмки (layout); абзац о базовой опоре — только у опоры-состояния
// статичного кадра (stateBase).
func textImagesPrompt(approved, notes, shotFrames, previous, layout, stateBase bool) string {
	prompt := "Создай перечисленные опорные изображения встроенным инструментом генерации изображений. Используй только переданные копии референсов. " +
		"references — что на каждой копии: file — имя копии, entity — ID сущности кастинга, name — её имя, kind — вид (например, character — персонаж, location — место, prop — предмет). " +
		"Когда промпт опоры или notes называют референс по имени (референс «Мастерская»), это копия с таким name; не определяй принадлежность копии по её содержимому. " +
		"Передай генератору все копии из referencePaths создаваемой опоры и в его промпте назови по name, какая копия чья. "
	if shotFrames {
		prompt += "Копия с полем shot — кадр уже принятого плана клипа с этим ID: бери из неё только то, что о ней говорит промпт опоры (место, свет, расположение предметов, позу, одежду); ракурс и крупность задаёт промпт опоры. "
	}
	if approved {
		prompt += "approvedFrames — уже утверждённые кадры этого же плана, основа создаваемой опоры: передай их генератору как референсы. " +
			"Промпт опоры описывает кадр целиком, в том числе то, что совпадает с утверждёнными: сохрани как на них всё, что он прямо не меняет " +
			"(внешность и одежду героев, форму и вид предметов, свет, место, ракурс, расстановку и направление транспорта и героев). "
		if notes {
			prompt += "Если notes создаваемой опоры просят взять за основу утверждённую опору, передай её генератору первым входом и редактируй её: " +
				"меняй только названное в notes, остальное сохрани как на ней, даже если промпт опоры описывает кадр иначе. "
		}
	}
	if notes {
		prompt += "notes — исправления пользователя к прежним вариантам: выполни их, они важнее промпта опоры и совпадения с прежним результатом. "
	}
	if layout {
		prompt += "frame — факты кадра по точке съёмки плана: start — первый кадр, end — последний (опора с role first берёт start, с role last — end, промежуточная — ближайший); " +
			"camera_height и tilt — высота камеры и наклон взгляда, objects и subjects — что видно, где по горизонтали, на каком расстоянии и что за краями кадра. " +
			"scheme — схема места: форма, размеры и высота объектов (line без smooth — прямые отрезки, elevation — подъём низа над землёй). " +
			"Генератор не переводит градусы в перспективу: в его промпте передай ракурс видимыми признаками (снизу вверх — видны дно предметов и нижние грани выступов, вертикали сходятся кверху; сверху вниз — виден верх предметов, земля заполняет фон), а форму ориентиров — как на схеме. " +
			"Посмотри результат: если ракурс, расстановка или форма ориентиров расходятся с frame и scheme (поднятый объект висит без опоры, прямые отрезки стали кривой, видно то, что за краем кадра), сгенерируй опору ещё раз с уточнённым промптом, не больше одного повтора. "
	}
	if previous {
		prompt += "previousFrames — прежний вариант создаваемой опоры с тем же id, к которому относятся notes: передай его генератору первым входом и редактируй его, если notes не велят взять за основу утверждённую опору. " +
			"Меняй только то, что называют notes, всё остальное (композицию, позу, лицо, свет, предметы) сохрани как на нём; заново рисуй кадр, только если notes этого прямо требуют. "
	}
	if stateBase {
		prompt += "stateBase — базовая опора статичного кадра: создаваемая опора — тот же кадр в другом состоянии, видео из них собирается без генерации, сменой изображений. " +
			"Если previousFrames нет, передай stateBase генератору первым входом и редактируй его: меняй только то, что промпт опоры называет изменившимся (какая секция горит, что на табло или экране), и прямые следствия этого — свет лампы, отблески и цвет света на ближайших поверхностях. " +
			"Композицию, ракурс, крупность, предметы, фон и свет сцены сохрани как на stateBase: заметный сдвиг кадра испортит смену состояний. "
	}
	return prompt +
		"Сохрани каждый результат как Kxx.png, Kxx.jpg или Kxx.webp в текущей папке, сохраняя фактический формат генератора. Не используй внешние сервисы генерации, API-ключи или другие генераторы. " +
		"Если встроенный image tool недоступен, сообщи об этом и не подменяй его другим способом. " +
		"Не изменяй референсы, исходный проект или принятые материалы. " +
		"В prompt каждого результата верни дословно промпт, который ты передал генератору для этого изображения (после повтора — последний). " +
		`Финальный ответ — один JSON без Markdown: {"schemaVersion":1,"stage":"frames","images":[{"id":"K01","path":"K01.png","prompt":"промпт генератора"}]}. ` +
		"Если какое-то изображение не создано, не добавляй его в images и добавь в ответ поле reason — одной-двумя фразами, что именно произошло, " +
		"дословно с сообщением генератора об отказе; если генератор отклонил запрос по правилам содержания (модерация), добавь ещё moderation=true."
}
